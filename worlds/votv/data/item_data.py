    internal_name: Optional[str] = ""
    classification: Optional[ItemClassification] = ItemClassification.filler
    unlock: Optional[list[str] | str] = ""

    def checkUnlock(self, whitelist:list[str]):
        if self.unlock != "":
            unlocks = []
            if type(self.unlock) == list:
                unlocks = self.unlock
            else:
                unlocks = [self.unlock]
            if not all(rule in whitelist for rule in unlocks):
                return False
        return True

